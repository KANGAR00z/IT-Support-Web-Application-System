/* =============================================================================
   FAST TICKET · theme.js — สีหลักของระบบ (โหลดต่อจาก Tailwind CDN ทุกหน้า)
   -----------------------------------------------------------------------------
   brand = สีของ "การกระทำ/แบรนด์" (ปุ่มหลัก, เมนูที่เลือก, ลิงก์, โฟกัส)
   เปลี่ยนสีองค์กรทั้งระบบ = แก้ BRAND ที่นี่ที่เดียว

   ห้ามใช้ brand กับสิ่งที่สีมี "ความหมาย" — พวกนั้นใช้สีตรงๆ เพื่อไม่ให้เปลี่ยนตาม:
     สถานะตั๋ว (amber/blue/emerald) · สีหมวดหมู่ · ป้ายบทบาท
   สีเขียว LINE (#06C755) ใช้เฉพาะปุ่มที่เป็นของ LINE เอง เช่น LINE Login
   ============================================================================= */
const BRAND = {
  50: '#eff6ff', 100: '#dbeafe', 200: '#bfdbfe', 300: '#93c5fd', 400: '#60a5fa',
  500: '#3b82f6', 600: '#2563eb', 700: '#1d4ed8', 800: '#1e40af', 900: '#1e3a8a'
};

tailwind.config = { theme: { extend: { colors: { brand: BRAND } } } };

// ให้ CSS ที่เขียนเองในหน้า (<style>) ใช้สีเดียวกันได้ผ่าน var(--brand-600)
document.documentElement.style.cssText += Object.keys(BRAND)
  .map(k => `--brand-${k}:${BRAND[k]};`).join('');
